import { expect, test } from "bun:test";
import { reviewRateLimitIp } from "./rate-limit-ip";

test.each([
  ["2001:db8:0:1::a", "2001:db8:0:1::/64"],
  ["2001:0DB8:0000:0001:abcd:0000:0000:0002", "2001:db8:0:1::/64"],
  ["2001:db8:0:2::a", "2001:db8:0:2::/64"],
  ["2001:db8::1", "2001:db8:0:0::/64"],
  ["2001:db8:1:2:3:4:192.0.2.7", "2001:db8:1:2::/64"],
  ["192.0.2.7", "192.0.2.7"],
  ["::ffff:192.0.2.7", "192.0.2.7"],
  ["0:0:0:0:0:FFFF:C000:0207", "192.0.2.7"],
  ["2001:::1", "2001:::1"],
  ["2001:db8::1]:12", "2001:db8::1]:12"],
])("maps %s to %s", (ip, expected) => {
  expect(reviewRateLimitIp(ip)).toBe(expected);
});
